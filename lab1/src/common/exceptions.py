"""
Общие исключения, используемые модулями проекта.

Module: common.exceptions
"""

# ---------------------------------------------------------------------------
# Classes
# ---------------------------------------------------------------------------

class PPOISError(Exception):
    """Базовое исключение всех модулей проекта."""


class StepLimitExceeded(PPOISError):
    """Превышен лимит шагов интерпретации абстрактной машины.

    Attributes:
        limit: Лимит шагов, который был превышен.
    """

    # -----------------------------------------------------------------------
    # Constructors
    # -----------------------------------------------------------------------

    def __init__(self, limit: int) -> None:
        """Создать исключение с указанием лимита.

        Args:
            limit: Максимальное число шагов, после которого
                интерпретация была прервана.
        """
        self.limit: int = limit
        super().__init__(
            f"машина не остановилась за {limit} шагов"
        )
