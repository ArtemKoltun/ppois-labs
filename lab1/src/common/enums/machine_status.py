"""
Состояние абстрактной машины в процессе интерпретации.

Module: common.enums.machine_status
"""

# ---------------------------------------------------------------------------
# Imports
# ---------------------------------------------------------------------------

from __future__ import annotations

from enum import Enum

# ---------------------------------------------------------------------------
# Classes
# ---------------------------------------------------------------------------

class MachineStatus(Enum):
    """Состояние абстрактной машины в процессе интерпретации.

    Используется машиной Тьюринга и нормальными алгорифмами Маркова
    для отображения текущего статуса в UI и в логах.

    Attributes:
        NOT_STARTED: Машина создана, но ни одного шага не выполнено.
        RUNNING: Машина выполнила хотя бы один шаг и не остановилась.
        HALTED: Машина остановилась — достигнуто конечное состояние
            или нет применимого правила.
    """

    NOT_STARTED = "not_started"
    RUNNING = "running"
    HALTED = "halted"

    # -----------------------------------------------------------------------
    # Magic methods
    # -----------------------------------------------------------------------

    def __str__(self) -> str:
        """Вернуть человекочитаемое название статуса.

        Returns:
            Строка вида ``"не запущена"``, ``"выполняется"`` или
            ``"остановлена"``.
        """
        names: dict[MachineStatus, str] = {
            MachineStatus.NOT_STARTED: "не запущена",
            MachineStatus.RUNNING: "выполняется",
            MachineStatus.HALTED: "остановлена",
        }
        return names[self]
