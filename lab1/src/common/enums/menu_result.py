"""
Результат выполнения пункта консольного меню.

Module: common.enums.menu_result
"""

# ---------------------------------------------------------------------------
# Imports
# ---------------------------------------------------------------------------

from __future__ import annotations

from enum import Enum

# ---------------------------------------------------------------------------
# Classes
# ---------------------------------------------------------------------------

class MenuResult(Enum):
    """Результат выполнения пункта консольного меню.

    Каждый пункт меню возвращает одно из этих значений, чтобы цикл
    меню знал, продолжать работу, вернуться в родительское меню или
    завершить программу.

    Attributes:
        CONTINUE: Остаться в текущем меню и продолжить работу.
        BACK: Вернуться в родительское меню.
        EXIT: Завершить работу программы.
    """

    CONTINUE = "continue"
    BACK = "back"
    EXIT = "exit"
