"""
Абстрактный интерфейс для записи объекта в текстовый поток.

Module: common.abstract.writable
"""

# ---------------------------------------------------------------------------
# Imports
# ---------------------------------------------------------------------------

from __future__ import annotations

from abc import ABC
from abc import abstractmethod
from typing import TextIO


# ---------------------------------------------------------------------------
# Classes
# ---------------------------------------------------------------------------

class Writable(ABC):
    """Объект, который можно записать в текстовый поток.

    Наследники реализуют ``__str__``, а методы :meth:`to_stream` и
    :meth:`__repr__` предоставляются базовым классом.
    """

    # -----------------------------------------------------------------------
    # Abstract methods
    # -----------------------------------------------------------------------

    @abstractmethod
    def __str__(self) -> str:
        """Вернуть текстовое представление объекта.

        Returns:
            Строка, полностью описывающая состояние объекта.
        """

    # -----------------------------------------------------------------------
    # Public methods
    # -----------------------------------------------------------------------

    def __repr__(self) -> str:
        """Вернуть отладочное представление объекта.

        Returns:
            Строка вида ``ClassName(text)``.
        """
        return f"{type(self).__name__}({self!s})"

    def to_stream(self, stream: TextIO) -> None:
        """Записать объект в текстовый поток.

        Args:
            stream: Открытый текстовый поток с методом ``write()``.

        Returns:
            Ничего не возвращает.
        """
        stream.write(str(self))
