"""
Абстрактное правило подстановки нормального алгорифма Маркова.

Module: markov_algorithms.domain.abstract.rule
"""

# ---------------------------------------------------------------------------
# Imports
# ---------------------------------------------------------------------------

from __future__ import annotations

from abc import abstractmethod

from common.abstract.readable import Readable
from common.abstract.writable import Writable

# ---------------------------------------------------------------------------
# Classes
# ---------------------------------------------------------------------------

class AbstractRule(Readable, Writable):
    """Абстрактное правило подстановки нормального алгорифма.

    Правило описывает замену левой части слова на правую.
    Конкретный формат правила задаётся реализацией.
    """

    # -----------------------------------------------------------------------
    # Abstract methods
    # -----------------------------------------------------------------------

    @abstractmethod
    def matches(self, word: str) -> bool:
        """Проверить, применимо ли правило к слову.

        Args:
            word: Слово, к которому применяется правило.

        Returns:
            ``True``, если левая часть правила входит в слово.
        """

    # -----------------------------------------------------------------------
    # Properties
    # -----------------------------------------------------------------------

    @property
    @abstractmethod
    def left(self) -> str:
        """Левая часть правила — что ищем.

        Returns:
            Строка символов.
        """

    @property
    @abstractmethod
    def right(self) -> str:
        """Правая часть правила — на что заменяем.

        Returns:
            Строка символов.
        """

    @property
    @abstractmethod
    def is_final(self) -> bool:
        """Признак заключительного правила.

        Returns:
            ``True``, если правило заключительное.
        """
