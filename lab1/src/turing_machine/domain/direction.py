"""
Направление движения головки машины Тьюринга.

Module: turing_machine.domain.direction
"""

# ---------------------------------------------------------------------------
# Imports
# ---------------------------------------------------------------------------

from __future__ import annotations

from enum import Enum


# ---------------------------------------------------------------------------
# Classes
# ---------------------------------------------------------------------------

class Direction(Enum):
    """Направление, в котором головка сдвигается после записи.

    Attributes:
        LEFT: Сдвиг головки на одну ячейку влево.
        RIGHT: Сдвиг головки на одну ячейку вправо.
        STAY: Головка остаётся на месте.
    """

    LEFT = "L"
    RIGHT = "R"
    STAY = "S"

    # -----------------------------------------------------------------------
    # Alternative constructors
    # -----------------------------------------------------------------------

    @classmethod
    def from_char(cls, char: str) -> "Direction":
        """Вернуть направление по его однобуквенному обозначению.

        Args:
            char: Символ ``"L"``, ``"R"`` или ``"S"`` в любом регистре.

        Returns:
            Соответствующий элемент перечисления :class:`Direction`.

        Raises:
            ValueError: Если символ не соответствует ни одному
                направлению.
        """
        try:
            return cls(char.upper())
        except ValueError as exc:
            raise ValueError(
                f"неизвестное направление: {char!r}"
            ) from exc
