"""
Абстрактное правило перехода машины Тьюринга.

Module: turing_machine.domain.abstract.rule
"""

# ---------------------------------------------------------------------------
# Imports
# ---------------------------------------------------------------------------

from __future__ import annotations

from abc import abstractmethod

from common.abstract.readable import Readable
from common.abstract.writable import Writable

# ---------------------------------------------------------------------------
# Classes
# ---------------------------------------------------------------------------

class AbstractRule(Readable, Writable):
    """Абстрактное правило перехода машины Тьюринга.

    Правило описывает, что делать машине, когда она находится
    в определённом состоянии и читает определённый символ.
    Конкретный формат правила задаётся реализацией.
    """

    # -----------------------------------------------------------------------
    # Abstract methods
    # -----------------------------------------------------------------------

    @abstractmethod
    def matches(self, state: str, symbol: str) -> bool:
        """Проверить, применимо ли правило к паре (состояние, символ).

        Args:
            state: Текущее состояние машины.
            symbol: Символ, прочитанный с ленты.

        Returns:
            ``True``, если правило применимо.
        """

    # -----------------------------------------------------------------------
    # Properties
    # -----------------------------------------------------------------------

    @property
    @abstractmethod
    def current_state(self) -> str:
        """Состояние, в котором применимо правило.

        Returns:
            Имя состояния.
        """

    @property
    @abstractmethod
    def read_symbol(self) -> str:
        """Символ, который должно прочитать правило.

        Returns:
            Строка длиной 1.
        """
