"""
Абстрактная лента машины Тьюринга.

Module: turing_machine.domain.abstract.tape
"""

# ---------------------------------------------------------------------------
# Imports
# ---------------------------------------------------------------------------

from __future__ import annotations

from abc import abstractmethod

from common.abstract.readable import Readable
from common.abstract.writable import Writable


# ---------------------------------------------------------------------------
# Classes
# ---------------------------------------------------------------------------

class AbstractTape(Readable, Writable):
    """Абстрактная лента: адресуемое хранилище символов.

    Лента не хранит позицию каретки — за неё отвечает отдельный
    класс :class:`Head`. Это позволяет менять способ хранения
    ячеек, не затрагивая логику перемещения.
    """

    # -----------------------------------------------------------------------
    # Abstract methods
    # -----------------------------------------------------------------------

    @abstractmethod
    def read(self, position: int) -> str:
        """Вернуть символ в заданной позиции.

        Args:
            position: Целочисленная координата ячейки.

        Returns:
            Символ в позиции ``position`` или ``blank``, если
            ячейка не инициализирована.
        """

    @abstractmethod
    def write(self, position: int, symbol: str) -> None:
        """Записать символ в заданную позицию.

        Args:
            position: Целочисленная координата ячейки.
            symbol: Строка длиной 1.

        Returns:
            Ничего не возвращает.
        """

    # -----------------------------------------------------------------------
    # Properties
    # -----------------------------------------------------------------------

    @property
    @abstractmethod
    def blank(self) -> str:
        """Символ пустой ячейки.

        Returns:
            Строка длиной 1.
        """
