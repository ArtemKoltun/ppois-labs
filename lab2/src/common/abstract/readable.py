"""
Абстрактный интерфейс для чтения объекта из текстового потока.

Module: common.abstract.readable
"""

# ---------------------------------------------------------------------------
# Imports
# ---------------------------------------------------------------------------

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Self, TextIO

# ---------------------------------------------------------------------------
# Classes
# ---------------------------------------------------------------------------

class Readable(ABC):
    """Объект, который можно прочитать из текстового потока.

    Наследники реализуют только :meth:`_parse`, а методы
    :meth:`from_stream` и :meth:`from_string` предоставляются
    базовым классом.
    """

    # -----------------------------------------------------------------------
    # Abstract methods
    # -----------------------------------------------------------------------

    @classmethod
    @abstractmethod
    def _parse(cls, text: str) -> Self:
        """Разобрать строку и вернуть новый экземпляр класса.

        Args:
            text: Строка с текстовым представлением объекта.

        Returns:
            Новый экземпляр класса, восстановленный из ``text``.

        Raises:
            ValueError: Если строка не соответствует формату.
        """

    # -----------------------------------------------------------------------
    # Public methods
    # -----------------------------------------------------------------------

    @classmethod
    def from_stream(cls, stream: TextIO) -> Self:
        """Прочитать объект из текстового потока.

        Args:
            stream: Открытый текстовый поток с методом ``read()``.

        Returns:
            Новый экземпляр класса, восстановленный из потока.

        Raises:
            ValueError: Если содержимое потока не соответствует
                формату.
        """
        content: str = stream.read().strip()
        return cls._parse(content)

    @classmethod
    def from_string(cls, text: str) -> Self:
        """Прочитать объект из строки.

        Args:
            text: Строка с текстовым представлением объекта.

        Returns:
            Новый экземпляр класса, восстановленный из ``text``.

        Raises:
            ValueError: Если строка не соответствует формату.
        """
        return cls._parse(text.strip())
